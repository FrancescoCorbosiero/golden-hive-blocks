<?php
/**
 * Write docs/blocks.md, the reference of every Golden Hive block, from the
 * blocks' own block.json and render.php (through the page checker's loader,
 * so the reference and the checker always agree).
 *
 *   php tools/block-reference.php           write docs/blocks.md
 *   php tools/block-reference.php --check   exit 1 if docs/blocks.md is stale (CI)
 */

if (PHP_SAPI !== 'cli') {
    exit; // never runnable over HTTP
}

require __DIR__ . '/page-check-core.php';

$root  = dirname(__DIR__);
$specs = ghb_pc_load_specs($root);
ksort($specs['blocks']);

/** A default, short enough for a table cell. */
function ghb_ref_value($value): string
{
    if (is_bool($value)) {
        return $value ? '`true`' : '`false`';
    }
    if (is_array($value)) {
        return $value ? count($value) . ' sample item' . (count($value) > 1 ? 's' : '') : '`[]`';
    }
    if (null === $value) {
        return '';
    }
    $text = (string) $value;
    if ('' === $text) {
        return '`""`';
    }
    if (mb_strlen($text) > 48) {
        $text = mb_substr($text, 0, 46) . '…';
    }
    return '`' . str_replace(array('|', '`'), array('\\|', "'"), $text) . '`';
}

$out   = array();
$out[] = '# Block reference';
$out[] = '';
$out[] = '<!-- Generated by tools/block-reference.php from blocks/*/block.json and render.php. Do not edit by hand: run php tools/block-reference.php. -->';
$out[] = '';
$out[] = 'Every Golden Hive block, its attributes and their defaults. A Golden Hive';
$out[] = 'block is drawn by the server, so in a page it is a single self-closing';
$out[] = 'comment: `<!-- wp:golden-hive/name {"attribute":"value"} /-->`. An attribute';
$out[] = 'left out takes its default. How to put pages together is in';
$out[] = '[pages.md](pages.md); `php tools/check-page.php page.html` checks a page';
$out[] = 'against this reference.';
$out[] = '';
$out[] = 'Every block also accepts WordPress\'s own `className`, `anchor`, `align`';
$out[] = 'and `style`.';
$out[] = '';

foreach ($specs['blocks'] as $name => $block) {
    $out[] = '## `' . $name . '` — ' . $block['title'];
    $out[] = '';
    if ('' !== $block['description']) {
        $out[] = $block['description'];
        $out[] = '';
    }
    if (!$block['attrs']) {
        $out[] = 'No attributes.';
        $out[] = '';
        continue;
    }
    $out[] = '| Attribute | Type | Default | Notes |';
    $out[] = '|---|---|---|---|';
    foreach ($block['attrs'] as $key => $spec) {
        $type  = is_array($spec['type']) ? implode(' or ', $spec['type']) : (string) $spec['type'];
        $notes = array();
        if (is_array($spec['enum'])) {
            $notes[] = 'one of ' . implode(', ', array_map(function ($v) {
                return '`' . $v . '`';
            }, $spec['enum']));
        }
        if (is_array($spec['items']) && $spec['items']) {
            $notes[] = 'items: ' . implode(', ', array_map(function ($v) {
                return '`' . $v . '`';
            }, $spec['items']));
        }
        $out[] = '| `' . $key . '` | ' . $type . ' | ' . ghb_ref_value($block['defaults'][$key] ?? null) . ' | ' . implode('; ', $notes) . ' |';
    }
    $out[] = '';
}

$markdown = implode("\n", $out);
$target   = $root . '/docs/blocks.md';

if (in_array('--check', $argv, true)) {
    if (!is_file($target) || file_get_contents($target) !== $markdown) {
        fwrite(STDERR, "docs/blocks.md is out of date: run php tools/block-reference.php\n");
        exit(1);
    }
    echo "docs/blocks.md is up to date\n";
    exit(0);
}

if (!is_dir(dirname($target))) {
    mkdir(dirname($target));
}
file_put_contents($target, $markdown);
echo 'wrote docs/blocks.md (' . count($specs['blocks']) . " blocks)\n";
